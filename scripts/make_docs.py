#!/usr/bin/env python3
"""Generate docs/benchmarks.md from the benchmark definitions (tables, layouts, subsets,
query descriptions, overrides). Re-run after changing src/bencholap/benchmarks/:

    uv run python scripts/make_docs.py
"""

from pathlib import Path

from bencholap import benchmarks

OUT = Path(__file__).resolve().parents[1] / "docs" / "benchmarks.md"

INTRO = {
    "tpch": """TPC-H models a wholesale supplier: 8 tables (lineitem and orders are the large ones) and 22
ad-hoc decision-support queries with joins, aggregations and subqueries. Data comes from
`tpcgen-cli` (byte-identical to the official `dbgen`). SF1 is about 1 GB of raw data (6 million
lineitem rows); queries use the specification's validation parameters (`qgen -d`), so SF1 results
are checked against the official answer set.""",
    "tpcds": """TPC-DS models a retailer selling through stores, catalogs and the web: 24 tables (7 fact tables
such as store_sales, 17 dimensions) and 99 queries with complex joins, CTEs, window functions,
ROLLUP, INTERSECT and correlated subqueries. Data comes from `tpcgen-cli` (byte-identical to
`dsdgen`). The queries use the specification's qualification parameters, so SF1 results are
checked against the kit's answer sets (except Q85 and Q93, see the benchmark definition).""",
    "clickbench": """ClickBench (by ClickHouse) is one wide table of anonymized web-analytics events (`hits`,
105 columns) and 43 queries typical of dashboards and ad-hoc analysis: scans, COUNT DISTINCT,
high-cardinality GROUP BY, string search, top-N and date-range reports. Data is ClickBench's own
Parquet dataset (100 files of about 1 million rows); SF N loads the first N files, so only SF100 is
the full ClickBench dataset. The queries and the load (raw table plus timestamp conversion) are
ClickBench's own Trino versions. ClickBench publishes no answers, so results are compared between
configurations only.""",
}


def main() -> None:
    lines = ["# Benchmarks, data and queries", "",
             "_Generated by `scripts/make_docs.py` from `src/bencholap/benchmarks/`._", "",
             "All benchmarks run on **Apache Iceberg tables** (Parquet files, format version 2) through an",
             "Iceberg REST catalog and S3-compatible storage, and the only engine plugin today is **Trino**",
             "(Iceberg connector). Other table formats or connectors (Hive, Delta Lake, ...) and other engines",
             "need a plugin; see \"Adding an engine\" in the README.", "",
             "Results are derived from TPC-H / TPC-DS / ClickBench and are not comparable to published results.", ""]
    for name in ("tpch", "tpcds", "clickbench"):
        b = benchmarks.load(name)
        lines += [f"## {b.title}", "", INTRO[name], "",
                  f"- Tables: {', '.join(f'`{t}`' for t in b.tables)}",
                  f"- Scale factors: {', '.join(b.scale_factors())}",
                  f"- Definition: [`src/bencholap/benchmarks/{name}/benchmark.yaml`](../src/bencholap/benchmarks/{name}/benchmark.yaml)",
                  ""]
        lines += ["### Table layouts", "", "| layout | published setup | what it is |", "|---|---|---|"]
        for lay in b.layouts.values():
            src = "; ".join(f"[{s['name']}]({s['url']})" for s in lay.sources)
            what = " ".join(lay.description.split()) + ("" if lay.validated else f" _{' '.join(lay.basis.split())}_")
            lines.append(f"| `{lay.name}`{' (default)' if lay.name == b.default_layout else ''} | "
                         f"{'yes: ' + src if lay.validated else 'no'} | {what} |")
        lines.append("")
        if b.subsets:
            lines += ["### Query subsets", ""]
            for sname, sub in b.subsets.items():
                lines.append(f"- `{sname}`: {' '.join(sub['description'].split())}")
            lines.append("")
        desc = b.descriptions()
        lines += ["### Queries", "", "| query | what it does | Trino override |", "|---|---|---|"]
        sf = b.scale_factors()[0]
        for q in b.queries:
            o = b.query(q, sf, "trino").override
            lines.append(f"| `{q}` | {desc.get(q, '')} | {o['reason'] if o else ''} |")
        lines.append("")
    lines += ["## Sources", "",
              "- TPC-H and TPC-DS specifications: https://www.tpc.org (query names and business questions above are",
              "  taken from the specifications; TPC-DS business questions from Appendix B, v2.10.0).",
              "- tpcgen-cli: https://github.com/datafusion-contrib/tpcgen-rs",
              "- ClickBench: https://github.com/ClickHouse/ClickBench", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
