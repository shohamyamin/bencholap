#!/usr/bin/env python3
"""Normalize raw qgen/dsqgen output into the canonical query files used by bencholap.

Only mechanical, spec-permitted rewrites are applied, and each file records them in its
header so every difference from the generator output is visible:

TPC-H (qgen -d, validation substitution parameters)
  * the Oracle-style row limit "where rownum <= N;" emitted by qgen's default build
    becomes a trailing "limit N" (spec 2.1.2.9 allows vendor row-limit syntax);
    "rownum <= -1" means "no limit" and is dropped.
  * "interval 'N' day (3)" -> "interval 'N' day" (the leading field precision is not
    supported by most engines and does not change semantics).

TPC-DS (kit templates + Appendix B qualification substitution parameters, rendered by
tpcds_qualification.py; the same queries are used at every scale factor)
  * "+ 30 days" date arithmetic -> "+ interval '30' day".

Usage: normalize.py <raw-generator-output-dir> <repo-benchmarks-dir>
"""

import re
import shutil
import sys
from pathlib import Path

ROWNUM = re.compile(r"^\s*where rownum <= (-?\d+);\s*$", re.MULTILINE)
DAY_PRECISION = re.compile(r"(interval\s+'\d+'\s+day)\s*\(\d+\)", re.IGNORECASE)
DAYS = re.compile(r"([+-])\s*(\d+)\s+days\b", re.IGNORECASE)


def normalize_tpch(sql: str) -> tuple[str, list[str]]:
    notes = []
    sql = sql.replace("-- using default substitutions\n", "")
    m = ROWNUM.search(sql)
    if m:
        n = int(m.group(1))
        sql = ROWNUM.sub("", sql).rstrip()
        if n > 0:
            assert sql.endswith(";"), sql[-50:]
            sql = sql[:-1].rstrip() + f"\nlimit {n};"
            notes.append(f"row limit 'where rownum <= {n}' -> 'limit {n}'")
        else:
            notes.append("dropped 'where rownum <= -1' (no row limit)")
    sql, k = DAY_PRECISION.subn(r"\1", sql)
    if k:
        notes.append("interval day precision '(3)' removed")
    return sql.strip() + "\n", notes


def normalize_tpcds(sql: str) -> tuple[str, list[str]]:
    notes = []
    sql, k = DAYS.subn(lambda m: f"{m.group(1)} interval '{m.group(2)}' day", sql)
    if k:
        notes.append("'+ N days' -> '+ interval 'N' day'")
    sql = "\n".join(line.rstrip() for line in sql.splitlines())
    return sql.strip() + "\n", notes


def _write(target: Path, header: list[str], sql: str, notes: list[str]) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(header + [f"-- normalized: {n}" for n in notes]) + "\n" + sql)


def main(raw: Path, out: Path) -> None:
    sys.path.insert(0, str(Path(__file__).parent))
    import tpcds_qualification as tq

    # TPC-H: per scale factor (Q11's fraction depends on SF)
    commit = (raw / "tpch" / "GENERATOR_COMMIT").read_text().strip()
    dest = out / "tpch" / "queries"
    if dest.exists():
        shutil.rmtree(dest)
    for sf_dir in sorted((raw / "tpch").glob("sf*")):
        for q in sorted(sf_dir.glob("q*.sql")):
            sql, notes = normalize_tpch(q.read_text())
            header = [f"-- TPC-H {q.stem.upper()} ({sf_dir.name}), generated by qgen -d -s {sf_dir.name[2:]}",
                      f"-- tpch-dbgen commit {commit}"]
            _write(dest / sf_dir.name / q.name, header, sql, notes)

    # TPC-DS: qualification queries, scale-factor independent
    commit = (raw / "tpcds" / "GENERATOR_COMMIT").read_text().strip()
    params = tq.parse_spec((raw / "tpcds" / "spec.txt").read_text())
    for sub in ("queries", "variants"):
        if (out / "tpcds" / sub).exists():
            shutil.rmtree(out / "tpcds" / sub)
    for n in range(1, 100):
        tpl = (raw / "tpcds" / "templates" / f"query{n}.tpl").read_text()
        sql, notes = normalize_tpcds(tq.render(tpl, params[n], n))
        header = [(f"-- TPC-DS Q{n:02d}: kit template query{n}.tpl with the specification's (v2.10.0, "
                  "Appendix B) qualification substitution parameters"),
                  f"-- tpcds-kit commit {commit}"]
        _write(out / "tpcds" / "queries" / "any" / f"q{n:02d}.sql", header, sql, notes)
    for v in sorted((raw / "tpcds" / "variants").glob("query*.tpl")):
        name = v.stem[len("query"):]
        n = int(re.match(r"\d+", name).group(0))
        sql, notes = normalize_tpcds(tq.render(v.read_text(), params[n], n))
        header = [f"-- TPC-DS approved query variant {v.name} with qualification parameters of query{n}",
                  f"-- tpcds-kit commit {commit}"]
        _write(out / "tpcds" / "variants" / f"q{int(name[:-1]):02d}{name[-1]}.sql", header, sql, notes)

    for bench in ("tpch", "tpcds"):
        answers = raw / bench / "answers"
        adest = out / bench / "answers"
        if adest.exists():
            shutil.rmtree(adest)
        shutil.copytree(answers, adest)
        (out / bench / "GENERATOR_COMMIT").write_text((raw / bench / "GENERATOR_COMMIT").read_text())


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
